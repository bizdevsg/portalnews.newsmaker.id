    economic_calendars (
        economic_calendar_category_id,
        date,
        time,
        country,
        impact,
        figures,
        previous,
        forecast,
        actual,
        sources,
        measures,
        usual_effect,
        frequency,
        next_released,
        notes,
        isBankHoliday,
        bankHolidayNote,
        why_trader_care,
        created_at,
        updated_at
    )
SELECT
    c.id,
    t.date_value,
    t.time_value,
    t.country,
    t.impact,
    t.figures,
    t.previous_value,
    t.forecast_value,
    t.actual_value,
    t.sources,
    t.measures,
    t.usual_effect,
    t.frequency,
    t.next_released,
    t.notes,
    t.isBankHoliday,
    t.bankHolidayNote,
    t.why_trader_care,
    NOW(),
    NOW()
FROM
    tmp_economic_calendar_import t
    JOIN economic_calendar_categories c ON TRIM(LOWER(c.country)) COLLATE utf8mb4_unicode_ci = TRIM(LOWER(t.country)) COLLATE utf8mb4_unicode_ci
    AND TRIM(LOWER(c.figures)) COLLATE utf8mb4_unicode_ci = TRIM(LOWER(t.figures)) COLLATE utf8mb4_unicode_ci
WHERE
    NOT EXISTS (
        SELECT 1
        FROM economic_calendars ec
        WHERE
            ec.date = t.date_value
            AND TRIM(LOWER(ec.time)) COLLATE utf8mb4_unicode_ci = TRIM(LOWER(t.time_value)) COLLATE utf8mb4_unicode_ci
            AND TRIM(LOWER(ec.country)) COLLATE utf8mb4_unicode_ci = TRIM(LOWER(t.country)) COLLATE utf8mb4_unicode_ci
            AND TRIM(LOWER(ec.figures)) COLLATE utf8mb4_unicode_ci = TRIM(LOWER(t.figures)) COLLATE utf8mb4_unicode_ci
    );

