        SELECT 1
        FROM economic_calendar_categories c
        WHERE
            TRIM(LOWER(c.country)) COLLATE utf8mb4_unicode_ci = TRIM(LOWER(t.country)) COLLATE utf8mb4_unicode_ci
            AND TRIM(LOWER(c.figures)) COLLATE utf8mb4_unicode_ci = TRIM(LOWER(t.figures)) COLLATE utf8mb4_unicode_ci
    )
GROUP BY
    t.country,
    t.impact,
    t.figures,
    t.sources,
    t.measures,
    t.usual_effect,
    t.frequency,
    t.next_released,
    t.notes,
    t.isBankHoliday,
