-- Insert category hanya jika kombinasi country + impact + figures belum ada
INSERT INTO
    economic_calendar_categories (
        country,
        impact,
        figures,
        sources,
        measures,
        usual_effect,
        frequency,
        next_released,
        notes,
        isBankHoliday,
        bankHolidayNote,
        why_trader_care,
        created_at,
        updated_at
    )
SELECT DISTINCT
    t.country,
    t.impact,
    t.figures,
    t.sources,
    t.measures,
    t.usual_effect,
    t.frequency,
    t.next_released,
    t.notes,
    t.isBankHoliday,
    t.bankHolidayNote,
    t.why_trader_care,
    NOW(),
    NOW()
FROM tmp_economic_calendar_import t
WHERE
    NOT EXISTS (
        SELECT 1
        FROM economic_calendar_categories c
        WHERE
            c.country COLLATE utf8mb4_unicode_ci = t.country COLLATE utf8mb4_unicode_ci
            AND c.impact COLLATE utf8mb4_unicode_ci = t.impact COLLATE utf8mb4_unicode_ci
            AND c.figures COLLATE utf8mb4_unicode_ci = t.figures COLLATE utf8mb4_unicode_ci
    );

