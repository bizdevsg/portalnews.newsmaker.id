    NOT EXISTS (
        SELECT 1
        FROM economic_calendars ec
        WHERE
            ec.date = t.date_value
            AND ec.time COLLATE utf8mb4_unicode_ci = t.time_value COLLATE utf8mb4_unicode_ci
            AND ec.country COLLATE utf8mb4_unicode_ci = t.country COLLATE utf8mb4_unicode_ci
            AND ec.figures COLLATE utf8mb4_unicode_ci = t.figures COLLATE utf8mb4_unicode_ci
    );

