        isBankHoliday,
        bankHolidayNote,
        why_trader_care,
        created_at,
        updated_at
    )
SELECT
    c.id,
    t.date_value,
    t.time_value,
    t.country,
    t.impact,
    t.figures,
    t.previous_value,
    t.forecast_value,
    t.actual_value,
    t.sources,
    t.measures,
    t.usual_effect,
    t.frequency,
    t.next_released,
    t.notes,
    t.isBankHoliday,
    t.bankHolidayNote,
    t.why_trader_care,
    NOW(),
    NOW()
FROM
    tmp_economic_calendar_import t
    JOIN economic_calendar_categories c ON c.country COLLATE utf8mb4_unicode_ci = t.country COLLATE utf8mb4_unicode_ci
    AND c.impact COLLATE utf8mb4_unicode_ci = t.impact COLLATE utf8mb4_unicode_ci
    AND c.figures COLLATE utf8mb4_unicode_ci = t.figures COLLATE utf8mb4_unicode_ci
